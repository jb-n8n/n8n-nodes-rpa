import { describe, expect, it } from 'vitest';
import { strToU8, zipSync } from 'fflate';
import { parseXml, unescapeXml, type XmlNode } from '../src/import/xml.js';
import { readZipEntries } from '../src/steps/zip.js';
import { timed, zeros, zip } from './zip-fixtures.js';

const node = (r: ReturnType<typeof parseXml>): XmlNode => {
  if ('error' in r) throw new Error(r.error);
  return r;
};
const errorOf = (r: ReturnType<typeof parseXml>): string | null => ('error' in r ? r.error : null);
const find = (n: XmlNode, name: string): XmlNode | undefined => {
  if (n.name === name) return n;
  for (const c of n.children) { const f = find(c, name); if (f) return f; }
  return undefined;
};

const XAML = `﻿<?xml version="1.0" encoding="utf-8"?>
<!-- generated by UiPath Studio -->
<Activity mc:Ignorable="sap sap2010" x:Class="Main"
  xmlns="http://schemas.microsoft.com/netfx/2009/xaml/activities"
  xmlns:ui="http://schemas.uipath.com/workflow/activities" xmlns:uix="http://schemas.uipath.com/workflow/activities/uix">
  <Sequence DisplayName="Log in &amp; export">
    <?some-processing instruction?>
    <ui:Click DisplayName='Click "Export"' ClickType="CLICK_SINGLE">
      <ui:Click.Target>
        <ui:Target Selector="&lt;webctrl tag='BUTTON' aaname='Export' /&gt;" WaitForReady="INTERACTIVE" />
      </ui:Click.Target>
    </ui:Click>
    <uix:NClick DisplayName="Click Save" Condition="[count > 0]">
      <uix:NClick.Target>
        <uix:TargetAnchorable FullSelectorArgument="&lt;webctrl tag='INPUT' /&gt;" FuzzySelectorArgument="&lt;webctrl aaname='Save' tag='INPUT' /&gt;" />
      </uix:NClick.Target>
    </uix:NClick>
    <ui:LogMessage Message="[&quot;done&quot;]"><![CDATA[a <b> & c]]> tail &#65;&#x42;&#x1F600;</ui:LogMessage>
  </Sequence>
</Activity>
`;

describe('parseXml', () => {
  it('parses a UiPath-style element with escaped selector attributes', () => {
    const root = node(parseXml(XAML));
    expect(root.name).toBe('Activity');
    expect(root.attrs['x:Class']).toBe('Main');
    expect(root.attrs['xmlns:uix']).toBe('http://schemas.uipath.com/workflow/activities/uix');
    const seq = root.children[0];
    expect(seq.name).toBe('Sequence');
    expect(seq.attrs.DisplayName).toBe('Log in & export');
    expect(seq.children.map((c) => c.name)).toEqual(['ui:Click', 'uix:NClick', 'ui:LogMessage']);
    const click = seq.children[0];
    expect(click.attrs).toEqual({ DisplayName: 'Click "Export"', ClickType: 'CLICK_SINGLE' });
    expect(find(click, 'ui:Target')!.attrs.Selector).toBe("<webctrl tag='BUTTON' aaname='Export' />");
    const nclick = seq.children[1];
    expect(nclick.attrs.Condition).toBe('[count > 0]');
    const target = find(nclick, 'uix:TargetAnchorable')!;
    expect(target.attrs.FullSelectorArgument).toBe("<webctrl tag='INPUT' />");
    expect(target.attrs.FuzzySelectorArgument).toBe("<webctrl aaname='Save' tag='INPUT' />");
    expect(target.children).toEqual([]);
    expect(target.text).toBe('');
    const log = seq.children[2];
    expect(log.attrs.Message).toBe('["done"]');
    // CDATA is character data taken verbatim; references in text are decoded.
    expect(log.text).toBe('a <b> & c tail AB\u{1F600}');
    expect(log.children).toEqual([]);
  });

  it('decodes the five entities and character references, and refuses invalid ones', () => {
    expect(node(parseXml(`<a v="&lt;&gt;&amp;&quot;&apos;&#9;&#x20AC;&#0065;">x &lt; y</a>`)))
      .toEqual({ name: 'a', attrs: { v: '<>&"\'\t€A' }, children: [], text: 'x < y' });
    for (const bad of ['&#0;', '&#x110000;', '&#xD800;', '&#xFFFE;', '&#1;', '&#99999999999999999999;', '&#X41;', '&#x;', '&#;', '&nbsp;', '&', '& b', '&amp', '&lt']) {
      expect(errorOf(parseXml(`<a>${bad}</a>`)), bad).toMatch(/reference|entity|&/);
      expect(errorOf(parseXml(`<a v="${bad}"/>`)), bad).toMatch(/reference|entity|&/);
    }
  });

  it('keeps namespace prefixes, self-closing tags and single or double quotes', () => {
    const r = node(parseXml(`<x:root a = 'one "1"' b="two '2'"><x:leaf/><leaf c="3"   /></x:root>`));
    expect(r).toEqual({
      name: 'x:root', attrs: { a: 'one "1"', b: "two '2'" }, text: '',
      children: [{ name: 'x:leaf', attrs: {}, children: [], text: '' }, { name: 'leaf', attrs: { c: '3' }, children: [], text: '' }],
    });
    // Line ends are normalised as an XML processor does; references to line ends survive.
    expect(node(parseXml('<a v="1\r\n2\n3\t4\r5&#xA;6">x\r\ny\rz</a>'))).toEqual({ name: 'a', attrs: { v: '1 2 3 4 5\n6' }, children: [], text: 'x\ny\nz' });
    // Text is the element's own character data, in order, not its children's.
    expect(node(parseXml('<a> one <b>two</b> three </a>')).text).toBe(' one  three ');
    // An attribute named __proto__ is stored as data, not as a prototype.
    const p = node(parseXml('<a __proto__="x" constructor="y"/>'));
    expect(p.attrs.__proto__).toBe('x');
    expect(Object.keys(p.attrs)).toEqual(['__proto__', 'constructor']);
    expect(({} as Record<string, unknown>).x).toBeUndefined();
  });

  it('rejects malformed documents with an error, never a throw', () => {
    const cases: [string, RegExp][] = [
      ['', /no root element/],
      ['   ', /no root element/],
      ['<!-- only a comment -->', /no root element/],
      ['<a></b>', /<\/b> does not close <a>/],
      ['<a><b></a></b>', /<\/a> does not close <b>/],
      ['</a>', /<\/a> has no open element/],
      ['<a>', /<a> is not closed/],
      ['<a><b/>', /<a> is not closed/],
      ['<a/><b/>', /more than one root element/],
      ['text<a/>', /text outside the root element/],
      ['<a/>text', /text outside the root element/],
      ['<a b="1" b="2"/>', /attribute b appears twice/],
      ['<a b="x<y"/>', /"<" in the value of attribute b/],
      ['<a b=1/>', /attribute b has no quoted value/],
      ['<a b/>', /attribute b has no quoted value/],
      ['<a "b"/>', /malformed tag/],
      ['< a/>', /malformed tag/],
      ['<a', /unterminated tag/],
      ['<a b="1"', /unterminated tag/],
      ['<a/ >', /malformed tag/],
      ['<a></a  x>', /malformed closing tag/],
      ['<a><!-- x </a>', /unterminated comment/],
      ['<a><![CDATA[ x </a>', /unterminated CDATA/],
      ['<?xml version="1.0"', /unterminated processing instruction/],
      ['<a><!ELEMENT a ANY></a>', /markup declarations are not allowed/],
    ];
    for (const [xml, want] of cases) {
      let out: ReturnType<typeof parseXml> | undefined;
      expect(() => { out = parseXml(xml); }, xml).not.toThrow();
      expect(errorOf(out!), xml).toMatch(want);
    }
  });

  it('refuses any DOCTYPE, so no entity is ever expanded', () => {
    const laughs = '<?xml version="1.0"?><!DOCTYPE lolz [<!ENTITY lol "lol"><!ENTITY lol2 "&lol;&lol;&lol;&lol;">]><lolz>&lol2;</lolz>';
    for (const xml of [laughs, '<!DOCTYPE html><html/>', '<!DOCTYPE a SYSTEM "file:///etc/passwd"><a/>', '<a><!DOCTYPE a></a>']) {
      expect(errorOf(parseXml(xml))).toBe('a DOCTYPE is not allowed');
    }
  });

  it('honours the depth and element caps, defaulting to 200 and 200,000', () => {
    const nest = (n: number) => '<a>'.repeat(n) + '</a>'.repeat(n);
    expect(errorOf(parseXml(nest(200)))).toBeNull();
    expect(errorOf(parseXml(nest(201)))).toBe('the XML is nested deeper than 200 elements');
    expect(errorOf(parseXml(nest(5), { maxDepth: 4 }))).toBe('the XML is nested deeper than 4 elements');
    const flat = (n: number) => '<r>' + '<a/>'.repeat(n - 1) + '</r>';
    expect(node(parseXml(flat(200_000))).children).toHaveLength(199_999);
    expect(errorOf(parseXml(flat(200_001)))).toBe('the XML has more than 200000 elements');
    expect(errorOf(parseXml(flat(11), { maxElements: 10 }))).toBe('the XML has more than 10 elements');
  });
});

describe('unescapeXml', () => {
  /** The decoder file-check used before the move; unescapeXml must match it exactly. */
  const previous = (s: string): string => s.replace(/&(#x[0-9a-fA-F]+|#\d+|lt|gt|amp|quot|apos);/g, (_m, e: string) => {
    if (e === 'lt') return '<';
    if (e === 'gt') return '>';
    if (e === 'amp') return '&';
    if (e === 'quot') return '"';
    if (e === 'apos') return "'";
    const code = e[1] === 'x' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
    try { return String.fromCodePoint(code); } catch { return ''; }
  });

  it('decodes exactly like the previous file-check decoder', () => {
    const fixed = ['', 'plain', '&lt;&gt;&amp;&quot;&apos;', '&amp;amp;', '&#65;&#x41;&#X41;&#x;&#;&#x1F600;', '&#x110000;&#99999999999999999999999;',
      '&#xD800;&#0;', '&nbsp; &LT; &lt &', '&&lt;;', '&#x12g;&#12a;', '&#x' + 'f'.repeat(400) + ';', '&#' + '9'.repeat(400) + ';'];
    for (const s of fixed) expect(unescapeXml(s), s).toBe(previous(s));
    const alphabet = ['&', '#', 'x', 'X', ';', 'l', 't', 'g', 'a', 'm', 'p', 'q', 'u', 'o', 's', '0', '1', '9', 'f', 'D', '8', ' ', '<'];
    let seed = 7;
    const rand = (n: number) => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed % n; };
    for (let i = 0; i < 20_000; i++) {
      let s = '';
      for (let k = rand(16); k > 0; k--) s += alphabet[rand(alphabet.length)];
      expect(unescapeXml(s), s).toBe(previous(s));
    }
  });
});

describe('adversarial input', () => {
  it('xml and zip limits hold on adversarial input', () => {
    // The target bound (200 ms) holds for depth 10,000 and a million elements; the other inputs get a looser 1,000 ms.
    const fast = (label: string, f: () => ReturnType<typeof parseXml>, want: RegExp, bound = 1000) => {
      const { out, ms } = timed(f);
      expect(errorOf(out), label).toMatch(want);
      expect(ms, label).toBeLessThan(bound);
      return ms;
    };
    const deep = '<a>'.repeat(10_000) + '</a>'.repeat(10_000);
    const million = '<r>' + '<a/>'.repeat(1_000_000) + '</r>';
    fast('depth 10,000', () => parseXml(deep), /nested deeper than 200/, 1000);
    fast('1 million self-closing elements', () => parseXml(million), /more than 200000 elements/, 1000);
    fast('unterminated attribute', () => parseXml('<a b="' + 'x'.repeat(5_000_000)), /unterminated tag/);
    fast('unterminated attribute before more markup', () => parseXml('<a b="x><c/><d/>'), /unterminated tag/);
    fast('a million ampersands', () => parseXml('<a>' + '&'.repeat(1_000_000) + '</a>'), /bare "&"/);
    fast('a million unterminated references', () => parseXml('<a>' + '&#1'.repeat(1_000_000) + '</a>'), /reference/);
    fast('a million open brackets', () => parseXml('<a>' + '<'.repeat(1_000_000)), /malformed tag/);
    fast('an unterminated comment', () => parseXml('<a><!--' + '-'.repeat(5_000_000)), /unterminated comment/);
    fast('many comment openers', () => parseXml('<a>' + '<!--'.repeat(1_000_000)), /unterminated comment/);
    fast('a long tag name', () => parseXml('<' + 'a'.repeat(5_000_000)), /unterminated tag/);
    fast('repeated attribute', () => parseXml('<a ' + 'x="1" '.repeat(500_000) + '/>'), /appears twice/);
    const many = timed(() => parseXml('<a ' + Array.from({ length: 100_000 }, (_v, i) => `k${i}="${i}"`).join(' ') + '/>'));
    expect(errorOf(many.out)).toBeNull();
    expect(many.ms).toBeLessThan(1000);
    const refs = timed(() => unescapeXml('&#'.repeat(1_000_000) + '&#x1'.repeat(1_000_000) + '&amp'.repeat(1_000_000)));
    expect(refs.out.length).toBe(10_000_000);
    expect(refs.ms).toBeLessThan(1000);

    // The import zip caps: a bomb, a declared-huge entry and too many entries come back as errors, quickly.
    const CAPS = { maxEntries: 2_000, perEntry: 4 * 1024 * 1024, total: 32 * 1024 * 1024 };
    const bomb = zip([{ name: 'Main.xaml', raw: zeros(256), usize: 100 }]);
    const tiny = zip(Array.from({ length: 2_001 }, (_v, i) => ({ name: `f${i}.xaml`, raw: Buffer.from('<a/>'), method: 0, usize: 4 })));
    const nested = Buffer.from(zipSync({ 'Main.xaml': strToU8(deep) }));
    for (const [z, want] of [[bomb, 'too-large'], [tiny, 'unreadable']] as const) {
      const { out, ms } = timed(() => readZipEntries(z, () => true, CAPS));
      expect(out instanceof Map ? null : out.error).toBe(want);
      expect(ms).toBeLessThan(1000);
    }
    const { out, ms } = timed(() => {
      const files = readZipEntries(nested, () => true, CAPS);
      if (!(files instanceof Map)) throw new Error(files.detail);
      return parseXml(files.get('Main.xaml')!.toString('utf8'));
    });
    expect(errorOf(out)).toMatch(/nested deeper than 200/);
    expect(ms).toBeLessThan(1000);
  });
});
